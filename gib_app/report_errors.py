BIGGEST_FIRST = ("dup", "bad_pay")      # крупные суммы сверху
PAIRED = ("dup", "same_name")           # строки идут группами: первый столбец — номер группы
PAIR_SHADE = "F1F5F9"


def _cell(ws, v, **style):
    c = WriteOnlyCell(ws, value=v)
    for k, val in style.items():
        setattr(c, k, val)
    return c


def write_errors_sheets(wb, details: dict) -> list:
    """→ названия созданных листов (если ошибок нет — один лист «Ошибки» с «не найдено»)."""
    made = [_sheet(wb, g, details[g]) for g in GROUPS if details.get(g)]
    if not made:
        ws = wb.create_sheet("Ошибки")
        title_rows(ws, "ОШИБКИ", "16A34A", "Ошибок не найдено ✓", 4)
        made.append("Ошибки")
    return made


def _sheet(wb, g, rows) -> str:
    name, color, hint, head, widths, money, dates = GROUPS[g]
    ws = wb.create_sheet(name)
    ws.sheet_properties.tabColor = color
    ws.sheet_view.showGridLines = False
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = f"A{HEAD_ROW + 1}"
    paired = g in PAIRED
    if g in BIGGEST_FIRST:
        rows = sorted(rows, key=lambda r: (-(r[4 + paired] or 0), r[0] if paired else 0))
    count = len({r[0] for r in rows}) if paired else len(rows)
    title_rows(ws, f"{name.upper()} — {count}", color, hint, len(widths))
    head_cells = [_cell(ws, h, font=Font(bold=True), fill=fill_color("E2E8F0"), border=BORDER, alignment=CENTER)
                  for h in ["№"] + head]
    head_cells[0].comment = Comment(hint, "Распределение по ГИБ", width=320, height=90)
    ws.append(head_cells)
    pair_no = {}
    for k, r in enumerate(rows, 1):
        if paired:                      # № — номер пары по порядку, пары через одну с фоном
            k = pair_no.setdefault(r[0], len(pair_no) + 1)
            r = r[1:]
        shade = {"fill": fill_color(PAIR_SHADE)} if paired and k % 2 == 0 else {}
        ws.append([_cell(ws, k, **shade)] + [
            _cell(ws, v, number_format=NUM, **shade) if i in money and v is not None
            else _cell(ws, v, number_format=DATE, **shade) if i in dates and v is not None
            else _cell(ws, v, **shade) for i, v in enumerate(r, 1)])
    ws.auto_filter.ref = f"A{HEAD_ROW}:{get_column_letter(len(widths))}{HEAD_ROW + len(rows)}"
    return name


def error_counts(details: dict) -> list:
    """Для экрана итога — те же числа, что на листах: [(лист, {файл: сколько}, всего)]. Двойной платёж
    считается в файле, где повтор; «одно название — разные ИНН» — по всем файлам сразу (без разбивки)."""
    out = []
    for g, (name, *_) in GROUPS.items():
        rows = details.get(g)
        if not rows:
            continue
        if g in ("same_name", "inn_names"):         # по всем файлам сразу: группы / ИНН
            out.append((name, {}, len({r[0] for r in rows})))
            continue
        if g == "dup":
            rows = [r[1:] for r in rows if r[6] == "повтор"]
        out.append((name, dict(Counter(r[0] for r in rows)), len(rows)))
    return out
