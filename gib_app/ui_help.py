"""Окно «Как пользоваться»: коротко — что нажимать и где что смотреть в результате."""
from PySide6.QtWidgets import QDialog, QDialogButtonBox, QTextBrowser, QVBoxLayout

from app_paths import BACKUP_FOLDER

HELP = f"""
<h2>ГИБ — «Заполнить ГИБ»</h2>
<ol>
<li>Выберите <b>выписку</b>.</li>
<li>Выберите <b>файл, куда заполнить</b> (например, Бучет).</li>
<li>Нажмите <b>«Заполнить ГИБ»</b> — платежи допишутся, суммы разложатся по столбцам ГИБ.</li>
</ol>
<p>Перед изменением делается копия в папку «{BACKUP_FOLDER}». Запускать повторно безопасно.<br>
<b>Зелёное</b> — вписала программа · <b>жёлтое</b> — проверьте (код ГИБ длиннее 4 цифр) ·
<b>красное в «Расходы»</b> — сумма не совпала с выпиской (наведите мышь — будет разница).</p>

<h2>Глубокий анализ</h2>
<ol>
<li>Перетащите в окно или выберите <b>файлы</b> — можно несколько.</li>
<li>У каждого файла появится <b>своя карточка</b>: выберите лист и впишите колонки — <b>ИНН</b> (обязательно),
<b>Название</b>, <b>Сумма</b>, <b>Итого</b>. Справа видно: «✓ готово» или «⚠ проверьте поля»
(неверное поле — с красной рамкой, наведите мышь — что не так).</li>
<li>Нажмите <b>«Анализ»</b> (внизу справа) — он нажимается, когда все карточки готовы.</li>
<li>Если частей больше двух — выберите, что с чем сравнивать (<b>«Было» → «Стало»</b>).</li>
<li>Нужна одна организация — впишите её ИНН в <b>«Один ИНН во всех файлах»</b> и нажмите «В Excel»:
все её строки из всех файлов, без ограничений по числу строк.</li>
<li>Готовый Excel — в папке «Свод по глубокому анализу».</li>
</ol>
<p><b>Как писать колонки:</b> <code>C</code> — вся колонка · <code>C5</code> — с 5-й строки ·
<code>C5-C300</code> — строки 5…300 · <code>G, H</code> — несколько колонок.<br>
<b>Итого</b> — колонка с итогом в каждой строке: если не равна сумме колонок «Сумма», организация подсвечивается.<br>
Остальные колонки файла программа не разбирает — они видны как есть на листе «Одна орг. во всех файлах».<br>
Файл не нужен — снимите галочку у его названия. Пустые файлы пропускаются сами.</p>

<h2>Где что смотреть в Excel</h2>
<ul>
<li><b>«Анализ»</b> — одна строка на организацию: суммы по файлам, изменение, ошибки.
Цвет строки — что случилось (новая, пропала, выросла…).</li>
<li><b>«Одна орг. во всех файлах»</b> — все строки организации из всех файлов.
Поставьте фильтр в колонке «ИНН». «Файлов» = 1 — организация есть только в одном файле.</li>
<li><b>«Ошибки»</b> — каждая ошибка строкой: файл, строка, что не так.</li>
<li><b>«Один ИНН — разные названия»</b>, <b>«Одно название — разные ИНН»</b> — возможные ошибки в данных.</li>
<li><b>«Итого не сходится»</b> — строки, где «Итого» не равно сумме колонок; на листе «Анализ» при наведении
на «Ошибки» видно, где и на сколько.</li>
<li><b>«Как считали»</b> — что и откуда взято.</li>
</ul>
<p>На листе «Анализ» наведите мышь на заголовок колонки или цвет — появится пояснение.</p>
"""


class HelpDialog(QDialog):
    def __init__(self, parent=None):
        super().__init__(parent)
        self.setWindowTitle("Как пользоваться")
        self.resize(640, 620)
        lay = QVBoxLayout(self)
        self.text = QTextBrowser()
        self.text.setHtml(HELP)
        lay.addWidget(self.text)
        buttons = QDialogButtonBox(QDialogButtonBox.Close)
        buttons.button(QDialogButtonBox.Close).setText("Закрыть")
        buttons.rejected.connect(self.reject)
        lay.addWidget(buttons)
